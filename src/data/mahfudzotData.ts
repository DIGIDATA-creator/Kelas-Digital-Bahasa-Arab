export function resolveMahfudzotCategory(arabic: string, translation: string, explanation: string = ''): string {
  const combined = (arabic + ' ' + translation + ' ' + explanation).toLowerCase();
  
  if (/teman|sahabat|pergaulan|shadiiq|jalis|صَدِيق|جَالِس|مَوَدَّة|صَادِق/i.test(combined)) {
    return 'Persahabatan';
  }
  if (/ilmu|belajar|buaian|membaca|akal|pengetahuan|العِلْم|تَعَلَّم|عَارِف|كِتَاب|عَالِم/i.test(combined)) {
    return 'Ilmu';
  }
  if (/sungguh|berjalan|kerja|usaha|cita|kepayahan|sampai|dapat|saara|jadda|سَارَ|جَدَّ|تَعَب|اجْتِهَاد/i.test(combined)) {
    return 'Kesungguhan';
  }
  if (/waktu|hari ini|esok|muda|masa|terlambat|telur|ayam|يَوْم|وَقْت|زَمَان/i.test(combined)) {
    return 'Waktu & Disiplin';
  }
  if (/jujur|sabar|adab|budi|lisan|lidah|mulia|dusta|dengki|shabara|صِدْق|صَبَر|أَدَب|خُلُق|مَلَام|حَسَد/i.test(combined)) {
    return 'Akhlak';
  }
  return 'Kebijaksanaan';
}

